import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { check } from './check.mjs';
import { loadBundle, posix, profile, toolDirectory, within } from './bundle.mjs';
import { currentSnapshot, isOutdated, pinnedSnapshot } from './snapshot.mjs';

export const marker = '<!-- Generated by project-okf-tools; edit concept metadata, then run index. -->';
const escape = value => String(value).replace(/\s+/g, ' ').replace(/[\\`*_[\]<>|]/g, '\\$&');
const encodePath = value => value.split('/').map(part => encodeURIComponent(part).replace(/[!'()*]/g, character => `%${character.charCodeAt(0).toString(16).toUpperCase()}`)).join('/');
const sorted = values => [...values].sort();

export function index(project) {
    const bundle = loadBundle(project);
    if (!bundle.config) throw new Error(bundle.diagnostics.map(d => d.message).join('\n'));
    const directories = new Set(['.']);
    for (const file of bundle.documents.keys()) {
        let directory = path.posix.dirname(file);
        while (directory !== '.') { directories.add(directory); directory = path.posix.dirname(directory); }
    }
    const writes = [];
    for (const directory of sorted(directories)) {
        const relative = path.posix.join(directory, 'index.md');
        const existing = bundle.documents.get(relative);
        if (existing && !existing.body.startsWith(`${marker}\n`)) throw new Error(`Preserving handwritten ${relative}; maintain it manually or explicitly replace it with a generated index.`);
        const lines = [];
        if (directory === '.') lines.push('---', `okf_version: "${profile.okfVersion}"`, '---');
        lines.push(marker, '', `# ${directory === '.' ? 'Documentation' : escape(path.posix.basename(directory))}`, '');
        for (const file of sorted(bundle.documents.keys())) {
            const base = path.posix.basename(file);
            if (path.posix.dirname(file) !== directory || ['index.md', 'log.md'].includes(base)) continue;
            const doc = bundle.documents.get(file);
            const title = doc.metadata?.title || base.replace(/\.md$/, '');
            const description = doc.metadata?.description || 'Legacy documentation awaiting review.';
            lines.push(`- [${escape(title)}](${encodePath(base)}) - ${escape(description)}`);
        }
        for (const child of sorted(directories)) {
            if (child === '.' || path.posix.dirname(child) !== directory) continue;
            const name = path.posix.basename(child);
            lines.push(`- [${escape(name)}](${encodePath(name)}/index.md) - ${escape(name)} documentation.`);
        }
        lines.push('');
        writes.push({ relative, file: path.join(bundle.root, relative), content: lines.join('\n') });
    }
    const proposedDocuments = new Map(writes.map(item => [item.relative, item.content]));
    const errors = check(project, { proposedDocuments }).filter(d => d.severity === 'error');
    if (errors.length) throw new Error(errors.map(d => `${d.file}: ${d.message}`).join('\n'));
    let changed = 0;
    for (const item of writes) {
        // Compare and write in the file's own line endings so CRLF checkouts are not rewritten.
        const current = fs.existsSync(item.file) ? fs.readFileSync(item.file, 'utf8') : undefined;
        if (current !== undefined && current.replace(/\r\n/g, '\n') === item.content) continue;
        fs.writeFileSync(item.file, current?.includes('\r\n') ? item.content.replace(/\n/g, '\r\n') : item.content);
        changed++;
    }
    return changed;
}

const runtimeFiles = ['bundle.mjs', 'check.mjs', 'scaffold.mjs', 'cli.mjs', 'verify.mjs', 'profile.json', 'profile.md', 'package.json', 'package-lock.json', 'snapshot.mjs'];

const workflowTemplate = (checkout = 'v7', node = '24') => `name: Documentation

on:
  push:
  pull_request:

permissions:
  contents: read

jobs:
  okf:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@${checkout}
      - uses: actions/setup-node@${checkout}
        with:
          node-version: ${node}
      - run: npm ci --prefix .okf/tools --ignore-scripts --no-audit --no-fund
      - run: node .okf/tools/cli.mjs check .
`;
// Earlier init releases wrote these workflows unchanged, so they count as managed too.
const managedWorkflows = [workflowTemplate(), workflowTemplate('v4', '22')];

function safeDestination(project, relative) {
    const absolute = path.resolve(project, relative);
    if (!within(project, absolute)) throw new Error(`Destination escapes project: ${relative}`);
    let current = absolute;
    while (current !== project) {
        const stat = fs.lstatSync(current, { throwIfNoEntry: false });
        if (stat?.isSymbolicLink()) throw new Error(`Destination contains a symlink: ${relative}`);
        if (current !== absolute && stat && !stat.isDirectory()) throw new Error(`Destination parent is not a directory: ${relative}`);
        current = path.dirname(current);
    }
    return absolute;
}

export function init(project) {
    project = fs.realpathSync(project);
    // Existing docs require a deliberate migration, not a partial automatic rewrite.
    for (const relative of ['.okf.json', '.okf', 'docs', '.github/workflows/okf.yml']) {
        const absolute = safeDestination(project, relative);
        const stat = fs.lstatSync(absolute, { throwIfNoEntry: false });
        if (stat && !(relative === 'docs' && stat.isDirectory() && fs.readdirSync(absolute).length === 0)) throw new Error(`Preserving existing ${relative}; initialize a fresh project or follow the migration procedure.`);
    }
    const files = new Map();
    files.set('.okf.json', `${JSON.stringify({ profile: profile.profile, bundle: 'docs', legacy: {}, missingLinks: {} }, null, 2)}\n`);
    files.set('.okf/.gitignore', 'tools/node_modules/\n');
    files.set('docs/overview.md', '---\ntype: Reference\ntitle: Project documentation\ndescription: Entry point for maintained project knowledge.\nstatus: draft\ngenerated:\n  by: process:okf-init\n---\n# Project documentation\n\nDescribe the project purpose, supported usage and links to its architecture and\nrunbooks. Replace this starter with project-specific facts before marking it stable.\n');
    files.set('docs/index.md', `---\nokf_version: "${profile.okfVersion}"\n---\n${marker}\n\n# Documentation\n\n- [Project documentation](overview.md) - Entry point for maintained project knowledge.\n`);
    files.set('.github/workflows/okf.yml', workflowTemplate());
    for (const file of runtimeFiles) files.set(`.okf/tools/${file}`, fs.readFileSync(path.join(toolDirectory, file)));
    // Read every source and validate every destination before the first write.
    for (const relative of files.keys()) {
        const absolute = safeDestination(project, relative);
        if (fs.existsSync(absolute)) throw new Error(`Preserving existing ${relative}.`);
    }
    for (const [relative, content] of files) {
        const destination = path.join(project, relative);
        fs.mkdirSync(path.dirname(destination), { recursive: true });
        fs.writeFileSync(destination, content, { flag: 'wx' });
    }
    return files.size;
}

function countMarkdown(directory) {
    if (!fs.existsSync(directory) || fs.lstatSync(directory).isSymbolicLink()) return 0;
    let count = 0;
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        if (entry.isSymbolicLink()) continue;
        if (entry.isDirectory() && !['node_modules', '.git'].includes(entry.name)) count += countMarkdown(path.join(directory, entry.name));
        else if (entry.isFile() && entry.name.endsWith('.md') && !['index.md', 'log.md'].includes(entry.name)) count++;
    }
    return count;
}

export function inventory(workspace, { outdatedOnly = false } = {}) {
    const projects = [];
    const current = currentSnapshot();
    for (const entry of fs.readdirSync(workspace, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
        if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
        const project = path.join(workspace, entry.name);
        if (!fs.existsSync(path.join(project, '.git'))) continue;
        const item = { name: entry.name, path: posix(path.resolve(project)), adoption: 'not-started', documents: countMarkdown(path.join(project, 'docs')), errors: 0, warnings: 0, profile: null, toolsVersion: null, outdated: false };
        if (fs.existsSync(path.join(project, '.okf.json'))) {
            const pinned = pinnedSnapshot(project);
            item.profile = pinned.profile;
            item.toolsVersion = pinned.toolsVersion;
            item.outdated = isOutdated(pinned, current);
            try {
                // A project pinned to an older profile is outdated, not invalid: count its documents
                // and leave findings to the upgrade command, which runs the project's own checker.
                const stale = pinned.profile !== current.profile;
                const bundle = loadBundle(project, stale ? { assumeProfile: pinned.profile } : {});
                if (!bundle.config) throw new Error(bundle.diagnostics.map(d => d.message).join('\n'));
                item.documents = [...bundle.documents.keys()].filter(f => !['index.md', 'log.md'].includes(path.posix.basename(f))).length;
                if (stale) {
                    item.errors = null;
                    item.warnings = null;
                    item.adoption = 'outdated';
                } else {
                    const diagnostics = check(project);
                    item.errors = diagnostics.filter(d => d.severity === 'error').length;
                    item.warnings = diagnostics.filter(d => d.severity === 'warning').length;
                    item.adoption = item.errors ? 'invalid' : item.outdated ? 'outdated' : Object.keys(bundle.config?.legacy || {}).length ? 'migrating' : 'adopted';
                }
            } catch (error) { item.adoption = 'invalid'; item.errors = 1; item.problem = error.message; }
        }
        if (!outdatedOnly || item.outdated) projects.push(item);
    }
    return projects;
}

const numeric = version => String(version).split('.').map(Number);
const older = (a, b) => {
    const [x, y] = [numeric(a), numeric(b)];
    for (let i = 0; i < 3; i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) < (y[i] || 0);
    return false;
};
const lf = text => text.replace(/\r\n/g, '\n');

function git(project, ...args) {
    const result = spawnSync('git', ['-C', project, ...args], { encoding: 'utf8' });
    if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${(result.stderr || result.error?.message || '').trim()}`);
    return result.stdout;
}

// Run an OKF checker's CLI against a project and return its findings, or why it could not run.
function runChecker(cli, project) {
    const result = spawnSync(process.execPath, [cli, 'check', project, '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    try {
        const parsed = JSON.parse(result.stdout);
        return { ok: true, errors: parsed.errors, warnings: parsed.warnings, diagnostics: parsed.diagnostics };
    } catch { return { ok: false, problem: (result.stderr || result.stdout || 'no output').trim().split(/\r?\n/)[0] }; }
}

const findingKey = d => `${d.severity}|${d.file}|${d.code}|${d.message}`;

export const migrationSteps = profileVersion => [
    `Profile ${profileVersion} predates the snapshots this command can upgrade safely (1.1.0 or newer); upgrade changed nothing.`,
    'Migrate it in a separate reviewed change:',
    '1. Run the pinned check (node .okf/tools/cli.mjs check .) and record its errors and warnings as the baseline.',
    '2. Follow "Upgrade an old snapshot" in docs/OKF.md (agent-skills): replace .okf/tools by hand with the files init writes, set .okf.json "profile" to the current profile, refresh the CI workflow.',
    '3. Run npm ci --prefix .okf/tools --ignore-scripts --no-audit --no-fund, then the new check. Fix new errors; profile 1.1.0 and later add provenance and review-date warnings, which belong in their own commit.',
    'After that, later upgrades are the one-command upgrade.',
];

function npmCi(project) {
    const result = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['ci', '--prefix', '.okf/tools', '--ignore-scripts', '--no-audit', '--no-fund'], { cwd: project, encoding: 'utf8', shell: process.platform === 'win32' });
    return { ok: result.status === 0, problem: (result.stderr || result.error?.message || '').trim().split(/\r?\n/)[0] };
}

// `install` is a seam for tests, which must not need the network.
export function upgrade(target, { dryRun = false, install = npmCi } = {}) {
    const project = fs.realpathSync(target);
    const current = currentSnapshot();
    const report = { project, dryRun, from: null, to: { profile: current.profile, toolsVersion: current.version }, status: 'upgraded', dirty: false, files: [], config: 'unchanged', workflow: 'absent', before: null, after: null, newFindings: [], notes: [] };
    const configPath = path.join(project, '.okf.json');
    if (!fs.existsSync(configPath)) throw new Error('No .okf.json; run init for a new project or follow the migration process for existing documentation.');
    if (posix(path.relative(project, toolDirectory)) === '.okf/tools') throw new Error('Run upgrade from the agent-skills source (tools/okf/cli.mjs), not from a project snapshot.');
    const pinned = pinnedSnapshot(project);
    report.from = { profile: pinned.profile, toolsVersion: pinned.toolsVersion };
    if (!pinned.configured || typeof pinned.profile !== 'string') throw new Error('.okf.json is not a readable object with a profile.');
    if (!pinned.hasTools) throw new Error('No .okf/tools snapshot; this project does not vendor its tools, so follow the migration process.');
    if (older(pinned.profile, '1.1.0')) {
        report.status = 'migration-required';
        report.steps = migrationSteps(pinned.profile);
        return report;
    }
    if (older(current.profile, pinned.profile)) throw new Error(`Project profile ${pinned.profile} is newer than this source's ${current.profile}; update agent-skills first.`);

    const status = git(project, 'status', '--porcelain').trim();
    report.dirty = status.length > 0;
    if (report.dirty && !dryRun) throw new Error(`Refusing to upgrade a dirty working tree; commit or stash first:\n${status}`);
    if (report.dirty) report.notes.push('Working tree has uncommitted changes; a real upgrade would refuse.');

    // Plan every write before touching anything.
    const writes = [];
    for (const file of runtimeFiles) {
        const relative = `.okf/tools/${file}`;
        const destination = safeDestination(project, relative);
        const content = fs.readFileSync(path.join(toolDirectory, file));
        const existing = fs.existsSync(destination) ? fs.readFileSync(destination) : null;
        const same = existing !== null && existing.equals(content);
        report.files.push({ file: relative, change: existing === null ? 'added' : same ? 'unchanged' : 'updated' });
        if (!same) writes.push({ destination, content });
    }
    const raw = fs.readFileSync(configPath, 'utf8');
    const profileField = /("profile"\s*:\s*)"[^"\r\n]*"/;
    if (!profileField.test(raw)) throw new Error('Cannot find a "profile" string in .okf.json.');
    const newConfig = raw.replace(profileField, `$1"${current.profile}"`);
    if (JSON.stringify(JSON.parse(newConfig)) !== JSON.stringify({ ...JSON.parse(raw), profile: current.profile })) throw new Error('Refusing an unsafe .okf.json edit.');
    if (newConfig !== raw) {
        writes.push({ destination: configPath, content: newConfig });
        report.config = `profile ${pinned.profile} -> ${current.profile}`;
    }
    const workflowPath = safeDestination(project, '.github/workflows/okf.yml');
    if (fs.existsSync(workflowPath)) {
        const text = fs.readFileSync(workflowPath, 'utf8');
        if (!managedWorkflows.includes(lf(text))) report.workflow = 'customized';
        else if (lf(text) === managedWorkflows[0]) report.workflow = 'current';
        else {
            report.workflow = 'refreshed';
            writes.push({ destination: workflowPath, content: text.includes('\r\n') ? managedWorkflows[0].replace(/\n/g, '\r\n') : managedWorkflows[0] });
        }
        if (report.workflow === 'customized') report.notes.push('.github/workflows/okf.yml differs from the managed template and was left alone; review it against the template by hand.');
    } else report.notes.push('No .github/workflows/okf.yml; CI is not enforcing the check.');

    // Before: the pinned tools. Borrow this source's parsers when the project has not installed its own.
    const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'okf-upgrade-'));
    try {
        const oldTools = path.join(project, '.okf', 'tools');
        let oldCli = path.join(oldTools, 'cli.mjs');
        if (!fs.existsSync(path.join(oldTools, 'node_modules'))) {
            fs.cpSync(oldTools, path.join(scratch, 'old'), { recursive: true });
            fs.cpSync(path.join(toolDirectory, 'node_modules'), path.join(scratch, 'old', 'node_modules'), { recursive: true });
            oldCli = path.join(scratch, 'old', 'cli.mjs');
            report.notes.push('Pinned tools had no installed dependencies; the before-check borrowed this source\'s parsers.');
        }
        report.before = runChecker(oldCli, project);
        if (dryRun) {
            try {
                const diagnostics = check(project, { assumeProfile: pinned.profile });
                report.after = { ok: true, errors: diagnostics.filter(d => d.severity === 'error').length, warnings: diagnostics.filter(d => d.severity === 'warning').length, diagnostics };
            } catch (error) { report.after = { ok: false, problem: error.message }; }
        } else {
            for (const { destination, content } of writes) {
                fs.mkdirSync(path.dirname(destination), { recursive: true });
                fs.writeFileSync(destination, content);
            }
            const installed = install(project);
            if (!installed.ok) report.notes.push(`npm ci failed (${installed.problem}); run it manually, then node .okf/tools/cli.mjs check .`);
            report.after = installed.ok ? runChecker(path.join(project, '.okf/tools/cli.mjs'), project) : { ok: false, problem: 'npm ci failed' };
        }
    } finally { fs.rmSync(scratch, { recursive: true, force: true }); }
    if (report.before?.ok && report.after?.ok) {
        const known = new Set(report.before.diagnostics.map(findingKey));
        report.newFindings = report.after.diagnostics.filter(d => !known.has(findingKey(d)));
    }
    return report;
}
